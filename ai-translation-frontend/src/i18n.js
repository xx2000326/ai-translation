export function t(key, params = {}, locale = 'zh') {
  let text = LOCALES[locale]?.[key] ?? LOCALES.zh[key] ?? key
  for (const [name, value] of Object.entries(params)) {
    text = text.replace(`{${name}}`, String(value))
  }
  return text
}
